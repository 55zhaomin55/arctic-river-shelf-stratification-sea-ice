function th_edges = make_edges_0_90(theta_centers_deg)

    c = ...
        theta_centers_deg(:)';


    n = ...
        numel(c);


    if n == 1

        th_edges = ...
            [0 90];

        return

    end


    mids = ...
        (c(1:end-1)+c(2:end))/2;


    th_edges = ...
        zeros(1,n+1);


    th_edges(1) = ...
        0;


    th_edges(2:n) = ...
        mids;


    th_edges(end) = ...
        90;

end


function rmax = draw_ring_sector_map_with_labels( ...
    ax, ...
    Z, ...
    P, ...
    r_edges, ...
    th_edges_deg, ...
    cmap, ...
    clims, ...
    missingColor, ...
    fmt, ...
    edgeLW, ...
    cellFont)

    [Nr,Nt] = ...
        size(Z);


    for i = Nr:-1:1

        r1 = ...
            r_edges(i);


        r2 = ...
            r_edges(i+1);


        for j = 1:Nt

            val = ...
                Z(i,j);


            t1 = ...
                deg2rad( ...
                th_edges_deg(j));


            t2 = ...
                deg2rad( ...
                th_edges_deg(j+1));


            nArc = ...
                32;


            tt_outer = ...
                linspace( ...
                t1,t2,nArc);


            tt_inner = ...
                linspace( ...
                t2,t1,nArc);


            x = [ ...
                r2*cos(tt_outer), ...
                r1*cos(tt_inner)];


            y = [ ...
                r2*sin(tt_outer), ...
                r1*sin(tt_inner)];


            %% --------------------------------------------------------
            % Cell color
            %% --------------------------------------------------------

            if isnan(val)

                fc = ...
                    missingColor;

            else

                fc = ...
                    value_to_rgb( ...
                    val, ...
                    cmap, ...
                    clims);

            end


            hp = patch( ...
                ax, ...
                x,y, ...
                fc, ...
                'EdgeColor','k', ...
                'LineWidth',edgeLW, ...
                'FaceAlpha',1);


            set( ...
                hp, ...
                'Clipping','off');


            %% --------------------------------------------------------
            % Cell text
            %% --------------------------------------------------------

            if isfinite(val)

                rc = ...
                    0.5*(r1+r2);


                tc = ...
                    0.5*(t1+t2);


                pval = ...
                    P(i,j);


                if isfinite(pval) && ...
                   pval < 0.05

                    txt = ...
                        sprintf( ...
                        '%.2f*', ...
                        val);

                else

                    txt = ...
                        sprintf( ...
                        fmt, ...
                        val);

                end


                text( ...
                    ax, ...
                    rc*cos(tc), ...
                    rc*sin(tc), ...
                    txt, ...
                    'FontName','Times New Roman', ...
                    'FontSize',cellFont, ...
                    'HorizontalAlignment','center', ...
                    'VerticalAlignment','middle', ...
                    'Color','k', ...
                    'Clipping','off');

            end

        end

    end


    rmax = ...
        max(r_edges);

end


function add_offset_labels_on_arc( ...
    ax, ...
    theta_centers_deg, ...
    offsets, ...
    rmax, ...
    fontSize)

    for k = 1:numel(theta_centers_deg)

        th = ...
            deg2rad( ...
            theta_centers_deg(k));


        x = ...
            1.04*rmax*cos(th);


        y = ...
            1.04*rmax*sin(th);


        text( ...
            ax, ...
            x,y, ...
            sprintf('%g',offsets(k)), ...
            'FontName','Times New Roman', ...
            'FontSize',fontSize, ...
            'HorizontalAlignment','center', ...
            'VerticalAlignment','middle', ...
            'Color','k', ...
            'Clipping','off');

    end

end


