function rgb = value_to_rgb( ...
    v, ...
    cmap, ...
    clims)

    v = ...
        max( ...
        min(v,clims(2)), ...
        clims(1));


    t = ...
        (v-clims(1)) / ...
        (clims(2)-clims(1));


    idx = ...
        1 + ...
        t*(size(cmap,1)-1);


    i0 = ...
        floor(idx);


    i1 = ...
        min( ...
        i0+1, ...
        size(cmap,1));


    w = ...
        idx-i0;


    i0 = ...
        max( ...
        1, ...
        min(i0,size(cmap,1)));


    rgb = ...
        (1-w)*cmap(i0,:) + ...
        w*cmap(i1,:);

end


function edges = centers_to_edges(centers)

    centers = ...
        centers(:)';


    n = ...
        numel(centers);


    edges = ...
        zeros(1,n+1);


    if n == 1

        edges = ...
            [centers(1)-0.5 ...
             centers(1)+0.5];

        return

    end


    mids = ...
        (centers(1:end-1) + ...
         centers(2:end))/2;


    edges(2:n) = ...
        mids;


    edges(1) = ...
        centers(1) - ...
        (mids(1)-centers(1));


    edges(n+1) = ...
        centers(end) + ...
        (centers(end)-mids(end));

end
