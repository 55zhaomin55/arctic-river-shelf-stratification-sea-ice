    1,2, ...
    'TileSpacing','compact', ...
    'Padding','compact');


fontAxis   = 7.5;
fontLabel  = 8.5;
fontLegend = 6.3;
fontPanel  = 10;


cols = ...
    lines(6);


%% ========================================================================
% 9. PANEL (a): 10-YEAR MOVING CORRELATIONS
%% ========================================================================

ax1 = ...
    nexttile(tl,1);


hold(ax1,'on');


yl = ...
    [-1 1];


%% ------------------------------------------------------------------------
% Light period background
%% ------------------------------------------------------------------------

patch( ...
    ax1, ...
    [min(yr_mid) 1990 1990 min(yr_mid)], ...
    [yl(1) yl(1) yl(2) yl(2)], ...
    [0.92 0.92 0.92], ...
    'EdgeColor','none', ...
    'FaceAlpha',0.18);


patch( ...
    ax1, ...
    [1990 2000 2000 1990], ...
    [yl(1) yl(1) yl(2) yl(2)], ...
    [0.88 0.88 0.88], ...
    'EdgeColor','none', ...
    'FaceAlpha',0.15);


patch( ...
    ax1, ...
    [2000 2010 2010 2000], ...
    [yl(1) yl(1) yl(2) yl(2)], ...
    [0.84 0.84 0.84], ...
    'EdgeColor','none', ...
    'FaceAlpha',0.12);


patch( ...
    ax1, ...
    [2010 max(yr_mid) max(yr_mid) 2010], ...
    [yl(1) yl(1) yl(2) yl(2)], ...
    [0.80 0.80 0.80], ...
    'EdgeColor','none', ...
    'FaceAlpha',0.10);


%% ------------------------------------------------------------------------
% Individual systems
%% ------------------------------------------------------------------------

h = ...
    gobjects(nBasin,1);


for ib = 1:nBasin

    h(ib) = ...
        plot( ...
        ax1, ...
        yr_mid, ...
        R(ib,:), ...
        '-', ...
        'Color',cols(ib,:), ...
        'LineWidth',0.95, ...
        'DisplayName',shortNames{ib});

end


%% ------------------------------------------------------------------------
% Regional mean
%% ------------------------------------------------------------------------

hMean = ...
    plot( ...
    ax1, ...
    yr_mid, ...
    Rmean, ...
    '-', ...
    'Color',[0 0 0], ...
    'LineWidth',2.20, ...
    'DisplayName','Regional mean');


%% ------------------------------------------------------------------------
% Period boundaries
%% ------------------------------------------------------------------------

xline( ...
    ax1, ...
    1990, ...
    '--', ...
    'Color',[0.25 0.25 0.25], ...
    'LineWidth',0.8);


xline( ...
    ax1, ...
    2000, ...
    '--', ...
    'Color',[0.25 0.25 0.25], ...
    'LineWidth',0.8);


xline( ...
    ax1, ...
    2010, ...
    '--', ...
    'Color',[0.25 0.25 0.25], ...
    'LineWidth',0.8);


%% ------------------------------------------------------------------------
% Zero line
%% ------------------------------------------------------------------------

yline( ...
    ax1, ...
    0, ...
    '--', ...
    'Color',[0.35 0.35 0.35], ...
    'LineWidth',0.8);


%% ------------------------------------------------------------------------
% Axes
%% ------------------------------------------------------------------------

xlim( ...
    ax1, ...
    [floor(min(yr_mid)) ...
     ceil(max(yr_mid))]);


ylim( ...
    ax1, ...
    yl);


xticks( ...
    ax1, ...
    1985:5:2020);


yticks( ...
    ax1, ...
    -1:0.2:1);


xlabel( ...
    ax1, ...
    'Window center year', ...
    'FontName','Times New Roman', ...
    'FontSize',fontLabel, ...
    'FontWeight','bold');


ylabel( ...
    ax1, ...
    '10-year running correlation', ...
    'FontName','Times New Roman', ...
    'FontSize',fontLabel, ...
    'FontWeight','bold');


grid(ax1,'on');


ax1.GridColor = ...
    [0.75 0.75 0.75];


ax1.GridAlpha = ...
    0.28;


set( ...
    ax1, ...
    'FontName','Times New Roman', ...
    'FontSize',fontAxis, ...
    'FontWeight','bold', ...
    'LineWidth',0.8, ...
    'TickDir','out', ...
    'Box','off', ...
    'Layer','top');


%% ------------------------------------------------------------------------
% Legend
%% ------------------------------------------------------------------------

lgd = ...
    legend( ...
    ax1, ...
    [h;hMean], ...
    'Location','southoutside', ...
    'Box','off', ...
    'Orientation','horizontal', ...
    'FontName','Times New Roman', ...
    'FontSize',fontLegend, ...
    'FontWeight','bold', ...
    'NumColumns',4);


lgd.ItemTokenSize = ...
    [8 4];


%% ------------------------------------------------------------------------
% Panel label
%% ------------------------------------------------------------------------

text( ...
    ax1, ...
    0.03, ...
    0.95, ...
    '(a)', ...
    'Units','normalized', ...
    'FontName','Times New Roman', ...
    'FontSize',fontPanel, ...
    'FontWeight','bold', ...
    'VerticalAlignment','top');


%% ========================================================================
% 10. PANEL (b): PERIOD DISTRIBUTIONS
%% ========================================================================

ax2 = ...
    nexttile(tl,2);


hold(ax2,'on');


valid = ...
    isfinite(Rmean) & ...
    isfinite(periodGroup);


R_box = ...
    Rmean(valid)';


G_box = ...
    periodGroup(valid)';


%% ------------------------------------------------------------------------
% Boxplot
%% ------------------------------------------------------------------------

boxplot( ...
    ax2, ...
    R_box, ...
    G_box, ...
    'Labels',periodLabels, ...
    'Symbol','', ...
    'Whisker',1.5, ...
    'Widths',0.55, ...
    'Colors',[0 0 0]);


%% ------------------------------------------------------------------------
% Box colors
%% ------------------------------------------------------------------------

