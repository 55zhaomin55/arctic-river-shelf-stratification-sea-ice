%% Repository-relative setup
thisDir = fileparts(mfilename('fullpath'));
codeDir = fileparts(thisDir);
addpath(codeDir,fullfile(codeDir,'functions'));
cfg = project_config();
sys = river_shelf_systems();
close all;

%% ========================================================================
% Figure 11
% Decadal variability of HSI-SIC relationships
%
% (a) 10-year moving correlations for six river-shelf systems
%     and regional mean
%
% (b) Distribution of regional-mean moving correlations
%     for four descriptive periods
%
% Period: 1979-2024
%
% IMPORTANT:
%   - Uses FINAL HSI_JAS_dt and SIC_JAS_dt directly from annual_river_shelf_metrics_1979_2024.mat
%   - No repeated detrending
%   - No old hard-coded results
%% ========================================================================




%% ========================================================================
% 1. LOAD FINAL DATA
%% ========================================================================

dataFile = fullfile(cfg.dataDir,'annual_river_shelf_metrics_1979_2024.mat');

D = load(dataFile);


%% ------------------------------------------------------------------------
% Required variables
%% ------------------------------------------------------------------------

if ~isfield(D,'HSI_JAS_dt')
    error('Annual metrics file does not contain HSI_JAS_dt.');
end

if ~isfield(D,'SIC_JAS_dt')
    error('Annual metrics file does not contain SIC_JAS_dt.');
end

if ~isfield(D,'years')
    error('Annual metrics file does not contain years.');
end


HSI_dt = ...
    double(D.HSI_JAS_dt);

SIC_dt = ...
    double(D.SIC_JAS_dt);

years = ...
    double(D.years(:));


%% ------------------------------------------------------------------------
% Convert orientation to 46 × 6
%% ------------------------------------------------------------------------

if size(HSI_dt,1) == 6 && ...
   size(HSI_dt,2) == 46

    HSI_dt = HSI_dt';

end


if size(SIC_dt,1) == 6 && ...
   size(SIC_dt,2) == 46

    SIC_dt = SIC_dt';

end


assert( ...
    isequal(size(HSI_dt),[46 6]), ...
    'HSI_JAS_dt must be 46 × 6.');


assert( ...
    isequal(size(SIC_dt),[46 6]), ...
    'SIC_JAS_dt must be 46 × 6.');


assert( ...
    numel(years) == 46, ...
    'years must contain 1979-2024.');


nYear = ...
    numel(years);

nBasin = ...
    6;


%% ========================================================================
% 2. SYSTEM NAMES
%% ========================================================================

basinNames = { ...
    'Mackenzie-Beaufort', ...
    'Yukon-Chukchi', ...
    'Kolyma-East Siberian', ...
    'Lena-Laptev', ...
    'Yenisei-Kara', ...
    'Ob-Kara'};


shortNames = { ...
    'Mackenzie', ...
    'Yukon', ...
    'Kolyma', ...
    'Lena', ...
    'Yenisei', ...
    'Ob'};


%% ========================================================================
% 3. 10-YEAR MOVING CORRELATIONS
%% ========================================================================

win = ...
    10;


nRun = ...
    nYear-win+1;


R = ...
    nan(nBasin,nRun);


P = ...
    nan(nBasin,nRun);


N = ...
    nan(nBasin,nRun);


yr_mid = ...
    nan(1,nRun);


%% ------------------------------------------------------------------------
% Window-center year
%
% For a 10-year window:
% 1979-1988 -> 1983.5
% ...
% 2015-2024 -> 2019.5
%% ------------------------------------------------------------------------

for iw = 1:nRun

    yr_mid(iw) = ...
        mean( ...
        years(iw:iw+win-1));

end


%% ------------------------------------------------------------------------
% Moving Pearson correlations
%% ------------------------------------------------------------------------

for ib = 1:nBasin

    x = ...
        HSI_dt(:,ib);

    y = ...
        SIC_dt(:,ib);


    for iw = 1:nRun

        xx = ...
            x(iw:iw+win-1);

        yy = ...
            y(iw:iw+win-1);


        valid = ...
            isfinite(xx) & ...
            isfinite(yy);


        N(ib,iw) = ...
            nnz(valid);


        if N(ib,iw) >= 5 && ...
           std(xx(valid)) > 0 && ...
           std(yy(valid)) > 0

            [R(ib,iw),P(ib,iw)] = ...
                corr( ...
                xx(valid), ...
                yy(valid), ...
                'Rows','complete');

        end

    end

end


%% ========================================================================
% 4. REGIONAL MEAN
%
% Keep arithmetic mean for consistency with manuscript definition.
%% ========================================================================

Rmean = ...
    mean( ...
    R, ...
    1, ...
    'omitnan');


%% ========================================================================
% 5. DESCRIPTIVE PERIODS
%
% Grouping is based on WINDOW-CENTER YEAR.
%% ========================================================================

periodGroup = ...
    nan(size(yr_mid));


periodGroup( ...
    yr_mid < 1990) = ...
    1;


periodGroup( ...
    yr_mid >= 1990 & ...
    yr_mid < 2000) = ...
    2;


periodGroup( ...
    yr_mid >= 2000 & ...
    yr_mid < 2010) = ...
    3;


periodGroup( ...
    yr_mid >= 2010) = ...
    4;


periodLabels = { ...
    '1979-1989', ...
    '1990-1999', ...
    '2000-2009', ...
    '2010-2024'};


%% ------------------------------------------------------------------------
% Period statistics
%% ------------------------------------------------------------------------

periodMean = ...
    nan(1,4);


periodMedian = ...
    nan(1,4);


periodN = ...
    nan(1,4);


for ip = 1:4

    tmp = ...
        Rmean(periodGroup == ip);


    tmp = ...
        tmp(isfinite(tmp));


    periodN(ip) = ...
        numel(tmp);


    if ~isempty(tmp)

        periodMean(ip) = ...
            mean(tmp);

        periodMedian(ip) = ...
            median(tmp);

    end

end


%% ========================================================================
% 6. DISPLAY RESULTS
%% ========================================================================

fprintf('\n============================================================\n');
fprintf('FIGURE 11: DECADAL HSI-SIC CORRELATION\n');
fprintf('============================================================\n');


fprintf('\nPeriod means based on window-center years:\n\n');


for ip = 1:4

    fprintf( ...
        '%-12s  mean = %.3f   median = %.3f   N = %d\n', ...
        periodLabels{ip}, ...
        periodMean(ip), ...
        periodMedian(ip), ...
        periodN(ip));

end


fprintf('\nFull moving-correlation range:\n');

fprintf( ...
    'Regional mean: %.3f to %.3f\n', ...
    min(Rmean,[],'omitnan'), ...
    max(Rmean,[],'omitnan'));


%% ========================================================================
% 7. SAVE INTERMEDIATE RESULTS
%% ========================================================================

outDir = cfg.outputDir;


if ~exist(outDir,'dir')
    mkdir(outDir);
end


save( ...
    fullfile( ...
    outDir, ...
    'Figure11_HSI_SIC_decadal_results.mat'), ...
    ...
    'R', ...
    'P', ...
    'N', ...
    'Rmean', ...
    'yr_mid', ...
    'periodGroup', ...
    'periodLabels', ...
    'periodMean', ...
    'periodMedian', ...
    'periodN', ...
    'years', ...
    'basinNames', ...
    'shortNames', ...
    'win');


%% ========================================================================
% 8. FIGURE SETTINGS
%% ========================================================================

