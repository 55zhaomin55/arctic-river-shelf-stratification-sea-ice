    0.28;


set( ...
    ax2, ...
    'FontName','Times New Roman', ...
    'FontSize',fontAxis, ...
    'FontWeight','bold', ...
    'LineWidth',0.8, ...
    'TickDir','out', ...
    'Box','off', ...
    'Layer','top');


%% ------------------------------------------------------------------------
% Panel label
%% ------------------------------------------------------------------------

text( ...
