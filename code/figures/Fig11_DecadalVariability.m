% Median lines
%% ------------------------------------------------------------------------

hMed = ...
    findobj( ...
    ax2, ...
    'Tag','Median');


for j = 1:length(hMed)

    set( ...
        hMed(j), ...
        'LineWidth',1.25, ...
        'Color','k');

end


%% ------------------------------------------------------------------------
% Period mean points
%% ------------------------------------------------------------------------

for ip = 1:4

    yy = ...
        Rmean( ...
        periodGroup == ip);


    yy = ...
        yy(isfinite(yy));


    if ~isempty(yy)

        plot( ...
            ax2, ...
            ip, ...
            mean(yy), ...
            'ko', ...
            'MarkerFaceColor','k', ...
            'MarkerSize',4.0);

    end

end


