    findobj( ...
    ax2, ...
    'Tag','Box');


boxColors = [ ...
    0.80 0.88 0.95
    0.64 0.80 0.92
    0.46 0.68 0.86
    0.26 0.52 0.78];


for j = 1:length(hBox)

    patch( ...
        ax2, ...
        get(hBox(j),'XData'), ...
        get(hBox(j),'YData'), ...
        boxColors(length(hBox)-j+1,:), ...
        'FaceAlpha',0.72, ...
        'EdgeColor','k');

end


